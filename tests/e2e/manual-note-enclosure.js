const here=import.meta.url.slice(0,import.meta.url.lastIndexOf('/')+1);
await import(here+'phase2-assembly.js?'+Date.now());
const H=window.__ui2,{store}=H;
const check=(ok,msg)=>{if(!ok)throw Error(msg);};
window.__noteEnclosure={run:async()=>{
 H.ready();await H.project({'plate.3dbx':H.GOLDEN+'locating-plate.3dbx'});await H.open('plate.3dbx');await H.waitFor(()=>store.getState().result?.mesh,20000,'part');await H.newDrawing();
 const s=()=>store.getState().drw,d=store.drawingStore,pg=()=>H.page();await H.waitFor(()=>pg()?.views.length===3,30000,'drawing views');
 const view=pg().views.find(v=>v.direction==='top');document.querySelector(`[data-view="${view.id}"]`).click();await H.wait(150);
 const id=d.addAnnotation({kind:'note',view:view.id,at:[0,0],text:'A',height:10});check(id,'note created');d.pick([{kind:'annotation',id}], 'replace');await H.wait(150);
 const select=await H.waitFor(()=>document.querySelector('[data-field="noteEnclosure"]'),5000,'note outline selector');
 const change=async(value)=>{select.value=value;select.dispatchEvent(new Event('change',{bubbles:true}));await H.wait(150);};
 await change('circle');check(pg().annotations.find(a=>a.id===id)?.enclosure==='circle','circle selected');
 await window.__shot?.('circle');
 const circle=[...document.querySelectorAll('[data-svg] polygon')].find(x=>(x.getAttribute('points')||'').split(' ').length>=96);
 const letter=[...document.querySelectorAll('[data-svg] text')].find(x=>x.textContent==='A');
 check(circle&&letter,'circle and letter rendered');
 const cb=circle.getBBox(),tb=letter.getBBox();
 check(Math.abs((cb.x+cb.width/2)-(tb.x+tb.width/2))<0.1,'single letter horizontally centred');
 d.setAnnotation(id,{text:'去毛邊\nNOTE',height:3.5});await H.wait(200);
 await change('rounded');check(pg().annotations.find(a=>a.id===id)?.enclosure==='rounded','rounded frame selected');
 await window.__shot?.('rounded');
 const polygon=[...document.querySelectorAll('[data-svg] polygon')].find(x=>(x.getAttribute('points')||'').split(' ').length>=52);check(polygon,'outline rendered');
 await change('');check(!pg().annotations.find(a=>a.id===id)?.enclosure,'outline removed');
 await change('rounded');
 H.next.save='outlined-note.3dbd';await H.action('檔案','儲存檔案');await H.waitFor(()=>!s().dirty,10000,'saved drawing');
 await H.action('檔案','新零件');await H.open('outlined-note.3dbd');
 await H.waitFor(()=>s()?.fileName==='outlined-note.3dbd' && pg()?.annotations.some(a=>a.id===id),30000,'reopened drawing');
 check(pg().annotations.find(a=>a.id===id)?.enclosure==='rounded','outline survives reopening');
 return {pass:true};
}};
